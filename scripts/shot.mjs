// Saves a screenshot into design/screenshots and keeps its README in step.
//
//   node scripts/shot.mjs add <image-file> <platform> <screen> <slug> "<purpose>" [--pair <name> --role before|after]
//   node scripts/shot.mjs readme
//
// platform: web | android-chrome | windows-host | validation | reference | design-review
// The file is copied (never moved or re-encoded) to
//   design/screenshots/<platform>/<screen>/<YYYY-MM-DD>-<HHMM>-<slug>[-before|-after].<ext>
// and recorded in design/screenshots/manifest.json. The README is generated from that manifest, so
// every screenshot has a stated purpose. Screenshots are evidence of the product's look over time; do not
// delete them in cleanups, and do not save duplicates or unrelated test output here.
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, extname, join, relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..", "design", "screenshots");
const manifestPath = join(root, "manifest.json");
const load = () => (existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, "utf8")) : []);

function pngSize(file) {
  const bytes = readFileSync(file);
  if (bytes.length > 24 && bytes.toString("latin1", 1, 4) === "PNG")
    return `${bytes.readUInt32BE(16)}x${bytes.readUInt32BE(20)}`;
  if (bytes[0] === 0xff && bytes[1] === 0xd8) {
    let i = 2;
    while (i < bytes.length) {
      if (bytes[i] !== 0xff) { i += 1; continue; }
      const marker = bytes[i + 1];
      if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker))
        return `${bytes.readUInt16BE(i + 7)}x${bytes.readUInt16BE(i + 5)}`;
      i += 2 + bytes.readUInt16BE(i + 2);
    }
  }
  return "unknown";
}

function readme(entries) {
  const groups = new Map();
  for (const entry of entries) {
    const key = `${entry.platform} / ${entry.screen}`;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(entry);
  }
  const lines = [
    "# Beacon Remote screenshots",
    "",
    "Every screenshot taken while building and reviewing Beacon Remote, organised by platform, screen and date.",
    "Originals are kept as captured (no re-encoding). **Do not delete these in cleanups.**",
    "",
    "- `reference/` is the approved design mockup, the intended product experience.",
    "- `web/` is the browser app; `android-chrome/` is the web app on a phone; `windows-host/` is the native Windows windows.",
    "- `validation/` is evidence from relay and device checks. `design-review/` holds before-and-after pairs from the design pass.",
    "- File names are `YYYY-MM-DD-HHMM-description[-before|-after]`. Times are UTC.",
    "- Captures that were deleted before this folder existed were recovered from the development session; they are the size the capture tool returned (phone shots are scaled to 900 px wide at most). Captures taken from now on keep their original resolution.",
    "- Screenshots of unrelated test steps and of anything private (notification shade, account data) are not kept here.",
    "- Add new ones with `node scripts/shot.mjs add <file> <platform> <screen> <slug> \"<purpose>\"` (use `--pair <name> --role before|after` for comparisons). This README is generated by `node scripts/shot.mjs readme`.",
    "",
  ];
  for (const [key, items] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`## ${key}`, "", "| File | When | Size | What it shows |", "| --- | --- | --- | --- |");
    for (const entry of items.sort((a, b) => a.file.localeCompare(b.file))) {
      const pair = entry.pair ? ` (${entry.role} · ${entry.pair})` : "";
      lines.push(`| [${basename(entry.file)}](${entry.file}) | ${entry.when} | ${entry.size} | ${entry.purpose}${pair} |`);
    }
    lines.push("");
  }
  writeFileSync(join(root, "README.md"), lines.join("\n"));
}

const [command, ...args] = process.argv.slice(2);
if (command === "readme") {
  readme(load());
} else if (command === "add") {
  const [source, platform, screen, slug, purpose, ...rest] = args;
  if (!source || !platform || !screen || !slug || !purpose) throw new Error("usage: shot.mjs add <file> <platform> <screen> <slug> \"<purpose>\" [--pair name --role before|after]");
  const option = (name) => { const at = rest.indexOf(name); return at >= 0 ? rest[at + 1] : undefined; };
  const pair = option("--pair");
  const role = option("--role");
  if ((pair && !["before", "after"].includes(role ?? "")) || (role && !pair)) throw new Error("--pair needs --role before|after");
  if (!statSync(source).isFile()) throw new Error("source is not a file");
  const now = new Date();
  const stamp = now.toISOString().slice(0, 10) + "-" + now.toISOString().slice(11, 13) + now.toISOString().slice(14, 16);
  const extension = extname(source).toLowerCase() || ".png";
  const name = `${stamp}-${slug}${role ? `-${role}` : ""}${extension}`;
  const target = join(root, platform, screen, name);
  mkdirSync(dirname(target), { recursive: true });
  copyFileSync(source, target);
  const entries = load();
  entries.push({
    file: relative(root, target).replaceAll("\\", "/"),
    when: `${stamp.slice(0, 10)} ${stamp.slice(11, 13)}:${stamp.slice(13)} UTC`,
    size: pngSize(target),
    platform,
    screen,
    purpose,
    ...(pair ? { pair, role } : {}),
    source: basename(source),
  });
  writeFileSync(manifestPath, JSON.stringify(entries, null, 2) + "\n");
  readme(entries);
  console.log(`Saved ${relative(process.cwd(), target)}`);
} else {
  throw new Error("usage: shot.mjs add|readme");
}
